"""Generate disabled, reviewable native scheduler files; never install or enable them."""
from __future__ import annotations

from datetime import time
import os
from pathlib import Path
import plistlib
import re


class ScheduleTemplateError(ValueError):
    """Fixed diagnostics that never repeat private user paths."""


def _safe_exec(path: Path) -> str:
    if not path.is_absolute() or not re.fullmatch(r"[A-Za-z0-9_./+\-]+", str(path)):
        raise ScheduleTemplateError("absolute_executable_path_required")
    return str(path)


def _safe_dir(path: Path, *, systemd: bool) -> str:
    if not path.is_absolute() or ".." in path.parts:
        raise ScheduleTemplateError("absolute_workdir_required")
    if systemd and not re.fullmatch(r"[A-Za-z0-9_./+\-]+", str(path)):
        raise ScheduleTemplateError("systemd_workdir_contains_unsupported_characters")
    return str(path)


def _parse_clock(value: str) -> time:
    if not isinstance(value, str) or not re.fullmatch(
        r"(?:[01]\d|2[0-3]):[0-5]\d", value
    ):
        raise ScheduleTemplateError("clock_must_be_HH_MM")
    return time.fromisoformat(value)


def _windows_wsl_script(
    *, executable: str, working_dir: str, distro: str,
    start: str, latest_start: str, ready_by: str,
) -> str:
    """PowerShell review-first registration script; no side effect when generated.

    All dynamic bash and PowerShell fragments are a strictly validated subset,
    not general shell input. Registration requires the operator to pass -Register.
    """
    if not re.fullmatch(r"[A-Za-z0-9_.-]+", distro):
        raise ScheduleTemplateError("invalid_wsl_distro")
    # WSL bash -lc cannot safely embed arbitrary paths in this template.
    if not re.fullmatch(r"[A-Za-z0-9_./+\\-]+", working_dir):
        raise ScheduleTemplateError("wsl_workdir_contains_unsupported_characters")
    if _parse_clock(latest_start) >= _parse_clock(ready_by):
        raise ScheduleTemplateError("cutoff_must_precede_ready_by")
    start_clock = _parse_clock(start)
    # Paths and distro are inserted only after strict metacharacter validation.
    linux_cmd = (
        f"cd {working_dir} && exec {executable} run "
        f"--expected-start {start} --latest-start {latest_start} "
        f"--ready-by {ready_by}"
    )
    return (
        "# Generated by Kushluk: REVIEW FIRST. No task exists until -Register.\n"
        "# Run under the intended Windows account (PowerShell, not Ubuntu).\n"
        "# Requires an installed WSL2 distro, a persistent Linux checkout, and\n"
        "# Windows logon; does NOT wake a sleeping/shut-down laptop or print.\n"
        "[CmdletBinding()]\n"
        "param([switch]$Register)\n"
        "$ErrorActionPreference = 'Stop'\n"
        "$taskName = 'Kushluk-WSL2-Morning'\n"
        f"$wslArgs = '-d {distro} -- bash -lc \"{linux_cmd}\"'\n"
        "if (-not $Register) {\n"
        "    Write-Host 'REVIEW ONLY: no scheduled task was registered.'\n"
        "    Write-Host ('Task: ' + $taskName)\n"
        "    Write-Host ('WSL arguments: ' + $wslArgs)\n"
        "    Write-Host 'After inspection, rerun this script with -Register.'\n"
        "    return\n"
        "}\n"
        "if (Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue) {\n"
        "    throw 'Task already exists; inspect before any changes.'\n"
        "}\n"
        "$action = New-ScheduledTaskAction -Execute \"$env:WINDIR\\System32\\wsl.exe\" -Argument $wslArgs\n"
        f"$at = (Get-Date).Date.AddHours({start_clock.hour}).AddMinutes({start_clock.minute})\n"
        "$trigger = New-ScheduledTaskTrigger -Daily -At $at\n"
        "$principal = New-ScheduledTaskPrincipal `\n"
        "    -UserId ([Security.Principal.WindowsIdentity]::GetCurrent().Name) `\n"
        "    -LogonType Interactive -RunLevel Limited\n"
        "$settings = New-ScheduledTaskSettingsSet `\n"
        "    -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `\n"
        "    -MultipleInstances IgnoreNew\n"
        "Register-ScheduledTask -TaskName $taskName -Action $action `\n"
        "    -Trigger $trigger -Principal $principal -Settings $settings `\n"
        "    -Description 'Kushluk digital-only WSL2 morning run' -ErrorAction Stop | Out-Null\n"
        "Write-Host ('Registered daily digital-only task: ' + $taskName)\n"
        "Write-Host 'To stop: Unregister-ScheduledTask -TaskName Kushluk-WSL2-Morning'\n"
    )


def templates(
    *, platform: str, executable: Path, working_dir: Path,
    start: str, latest_start: str, wsl_distro: str = "Ubuntu-24.04",
    ready_by: str = "08:00",
) -> dict[str, str]:
    """Render native OS units in memory. Not even an executable is launched."""
    if platform not in {"systemd", "launchd", "windows-wsl"}:
        raise ScheduleTemplateError("unsupported_platform")
    exec_path = _safe_exec(executable)
    workdir = _safe_dir(working_dir, systemd=platform in {"systemd", "windows-wsl"})
    start_time = _parse_clock(start)
    cutoff_time = _parse_clock(latest_start)
    if start_time >= cutoff_time:
        raise ScheduleTemplateError("start_must_precede_latest_start")
    h, m = start_time.hour, start_time.minute

    if platform == "windows-wsl":
        return {"kushluk-windows-wsl.ps1": _windows_wsl_script(
            executable=exec_path, working_dir=workdir, distro=wsl_distro,
            start=start, latest_start=latest_start, ready_by=ready_by,
        )}

    if platform == "systemd":
        service = (
            "[Unit]\n"
            "Description=Generate the local Kushluk morning edition\n"
            "Documentation=https://github.com/interzettel/kushluk\n"
            "\n[Service]\n"
            "Type=oneshot\n"
            f"WorkingDirectory={workdir}\n"
            f"ExecStart={exec_path} run --latest-start {latest_start} --expected-start {start}\n"
            "UMask=0077\n"
            "NoNewPrivileges=true\n"
            "\n[Install]\n"
            "WantedBy=default.target\n"
        )
        timer = (
            "[Unit]\n"
            "Description=Run local Kushluk edition every morning\n"
            "\n[Timer]\n"
            f"OnCalendar=*-*-* {h:02d}:{m:02d}:00\n"
            "Persistent=true\n"
            "AccuracySec=1min\n"
            "Unit=kushluk.service\n"
            "\n[Install]\n"
            "WantedBy=timers.target\n"
        )
        return {"kushluk.service": service, "kushluk.timer": timer}

    # launchd runs in the logged-in user's session, not a persistent headless host.
    # Explicit argument array (not a shell command) prevents quoting/injection.
    plist = {
        "Label": "org.interzettel.kushluk.morning",
        "ProgramArguments": [exec_path, "run", "--latest-start", latest_start,
                             "--expected-start", start],
        "WorkingDirectory": workdir,
        "StartCalendarInterval": {"Hour": h, "Minute": m},
        "RunAtLoad": False,
        "Umask": 0o077,
        "StandardOutPath": str(working_dir / "kushluk-scheduler.stdout.log"),
        "StandardErrorPath": str(working_dir / "kushluk-scheduler.stderr.log"),
    }
    return {
        "org.interzettel.kushluk.morning.plist":
            plistlib.dumps(plist, sort_keys=True).decode("utf-8")
    }


def export_templates(
    *, platform: str, executable: Path, working_dir: Path, output_dir: Path,
    start: str, latest_start: str, wsl_distro: str = "Ubuntu-24.04",
    ready_by: str = "08:00",
) -> list[str]:
    """Write create-only 0600 files; do not call systemctl, launchctl or CUPS."""
    rendered = templates(
        platform=platform, executable=executable, working_dir=working_dir,
        start=start, latest_start=latest_start, wsl_distro=wsl_distro,
        ready_by=ready_by,
    )
    if not output_dir.is_absolute() or ".." in output_dir.parts or output_dir.is_symlink():
        raise ScheduleTemplateError("absolute_output_dir_required")
    try:
        output_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
    except OSError as exc:
        raise ScheduleTemplateError("output_directory_unavailable") from exc
    if any((output_dir / name).exists() or (output_dir / name).is_symlink()
           for name in rendered):
        raise ScheduleTemplateError("schedule_files_exist")
    created = []
    try:
        for name, body in rendered.items():
            path = output_dir / name
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            created.append(path)
            with os.fdopen(fd, "w", encoding="utf-8") as stream:
                stream.write(body)
                stream.flush()
                os.fsync(stream.fileno())
        return sorted(rendered)
    except OSError as exc:
        for path in created:
            path.unlink(missing_ok=True)
        raise ScheduleTemplateError("schedule_export_failed") from exc
